#!/bin/bash
set -euo pipefail

echo " 1. Запуск фонового процесу sleep 1000 "
sleep 1000 &
sleep_pid=$!
echo "Процес sleep 1000 запущено у фоні з PID: $sleep_pid"
echo "--------------------------------------------------------"

echo " 2. Визначення ідентифікатора батьківського процесу (PPID) "
ps -o pid,ppid,command -p "$sleep_pid"
echo "--------------------------------------------------------"

echo " 3. Демонстрація pstree для нашого процесу "
pstree -p "$sleep_pid" || true
echo "--------------------------------------------------------"

echo " 4. Завдання (Варіант 8): Виведення процесів (PID, Користувач, Команда, Час запуску) "
ps -eo pid,user,comm,lstart | head -n 15
echo "..."
echo "--------------------------------------------------------"

echo " 5. Припинення виконання (завершення) створеного фонового процесу "
kill "$sleep_pid"
echo "--------------------------------------------------------"

